import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
await ctx.addInitScript(() => localStorage.setItem('frelux_cookie_consent', JSON.stringify({version:2,categories:{essential:true,analytics:true,advertising:true},timestamp:Date.now(),source:'banner'})));
const p = await ctx.newPage();
p.on('console', (m) => console.log('[' + m.type() + ']', m.text().slice(0, 200)));
await p.goto('http://localhost:4173/', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(12000);
console.log('units:', await p.evaluate(() => document.querySelectorAll('.frelux-ad-unit').length));
console.log('cfg:', await p.evaluate(() => JSON.stringify({ providers: (window.__ADCFG__||null) })));
await b.close();
