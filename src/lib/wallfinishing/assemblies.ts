  Object.fromEntries(WALLFIN_ASSEMBLIES.map((a) => [a.id, a]));

export function getAssembly(id: string): WallAssemblyTemplate | null {
  return WALLFIN_ASSEMBLY_MAP[id] ?? null;
}

export function getAssembliesForCountry(code: string): WallAssemblyTemplate[] {
  return WALLFIN_ASSEMBLIES.filter((a) =>
    a.id.startsWith(`${code.toLowerCase()}-`),
  );
}
