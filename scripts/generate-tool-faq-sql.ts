/**
 * Generates the tool FAQ migration and its seed manifest from the registries.
 *
 * The registries in src/config are the source of truth: the page renders them,
 * the structured data is built from them, and this script writes them to the
 * database so the same content is queryable, editable and available to other
 * surfaces. Running it twice produces byte-identical output, so a diff means
 * content changed, not that the generator moved something around.
 *
 * Usage: npm run faqs:sql
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { buildFaqDbRows } from "../src/config/faq-db-rows";

const MIGRATION = resolve(
  "supabase/migrations/20261031770000_tool_faq_articles.sql",
);
const MANIFEST = resolve("supabase/seed/tool-faq-articles.json");

const rows = buildFaqDbRows();

/** jsonb literal in dollar quotes: the content contains apostrophes. */
function jsonb(value: unknown, tag: string): string {
  return `$${tag}$${JSON.stringify(value)}$${tag}$`;
}

function literal(text: string): string {
  return `'${text.replace(/'/g, "''")}'`;
}

const values = rows
  .map(
    (row) =>
      `  (${literal(row.slug)}, ${literal(row.name)}, ${literal(row.route)}, ${literal(
        row.category,
      )}, ${row.question_count}, ${jsonb(row.questions, "q")}, ${jsonb(
        row.article,
        "a",
      )}, ${jsonb(row.seo, "s")}, ${row.word_count}, ${literal(row.source)})`,
  )
  .join(",\n");

const sql = `-- Tool FAQ articles: the content behind every /faq/:slug page.
--
-- Generated by scripts/generate-tool-faq-sql.ts from the registries in
-- src/config. Do not edit by hand: change the copy there and run
-- npm run faqs:sql. Public read, admin write, one row per tool.
BEGIN;

CREATE TABLE IF NOT EXISTS public.tool_faq_articles (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  route TEXT NOT NULL,
  category TEXT NOT NULL,
  question_count INTEGER NOT NULL DEFAULT 0,
  questions JSONB NOT NULL DEFAULT '[]'::jsonb,
  article JSONB NOT NULL DEFAULT '{}'::jsonb,
  seo JSONB NOT NULL DEFAULT '{}'::jsonb,
  word_count INTEGER NOT NULL DEFAULT 0,
  source TEXT NOT NULL DEFAULT 'registry',
  published BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tool_faq_articles_category
  ON public.tool_faq_articles(category, published);

COMMENT ON TABLE public.tool_faq_articles IS
  'Questions, long form articles and SEO metadata for each tool FAQ page. Generated from src/config/flavour registries.';

ALTER TABLE public.tool_faq_articles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read published tool FAQs" ON public.tool_faq_articles;
CREATE POLICY "Public can read published tool FAQs"
  ON public.tool_faq_articles FOR SELECT
  USING (published = true);

DROP POLICY IF EXISTS "Admins can manage tool FAQs" ON public.tool_faq_articles;
CREATE POLICY "Admins can manage tool FAQs"
  ON public.tool_faq_articles FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
      AND profiles.role = 'admin'
    )
  );

GRANT SELECT ON public.tool_faq_articles TO anon, authenticated;
GRANT ALL ON public.tool_faq_articles TO service_role;

INSERT INTO public.tool_faq_articles
  (slug, name, route, category, question_count, questions, article, seo, word_count, source)
VALUES
${values}
ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name,
  route = EXCLUDED.route,
  category = EXCLUDED.category,
  question_count = EXCLUDED.question_count,
  questions = EXCLUDED.questions,
  article = EXCLUDED.article,
  seo = EXCLUDED.seo,
  word_count = EXCLUDED.word_count,
  source = EXCLUDED.source,
  published = true,
  updated_at = now();

DO $$
DECLARE
  row_count INTEGER;
  short_count INTEGER;
BEGIN
  SELECT count(*) INTO row_count FROM public.tool_faq_articles;
  -- The registry holds groups of five to eight questions, so the rule is a
  -- floor plus agreement between the stored count and the stored array. An
  -- assertion of exactly five failed the moment a six question tool was added.
  SELECT count(*) INTO short_count
    FROM public.tool_faq_articles
    WHERE question_count < 5
       OR question_count <> jsonb_array_length(questions);
  IF short_count > 0 THEN
    RAISE EXCEPTION 'tool_faq_articles has % rows whose question count disagrees with their questions', short_count;
  END IF;
  RAISE NOTICE 'tool_faq_articles: % rows, % long form', row_count,
    (SELECT count(*) FROM public.tool_faq_articles WHERE source = 'longform');
END $$;

COMMIT;
`;

writeFileSync(MIGRATION, sql, "utf8");
writeFileSync(MANIFEST, `${JSON.stringify(rows, null, 2)}\n`, "utf8");

const longCount = rows.filter((row) => row.source === "longform").length;
console.log(
  `wrote ${MIGRATION}\nwrote ${MANIFEST}\n${rows.length} rows, ${rows.reduce(
    (sum, row) => sum + row.question_count,
    0,
  )} questions, ${longCount} long form`,
);
