#!/usr/bin/env node
/**
 * IFC conformance harness: run the real loader over a directory of .ifc files
 * and record, per file, exactly what happened.
 *
 * This is EVIDENCE, not certification. buildingSMART issues certification;
 * this script only makes the loader's behaviour over a corpus visible and
 * reproducible, so a claim can point at a report instead of a feeling.
 *
 * Usage:
 *   npx tsx scripts/ifc-conformance-report.ts <corpus-dir> [--out docs/ifc-conformance-report.md]
 *
 * The corpus is not vendored: download the official buildingSMART validation
 * files (IFC2x3, IFC4, IFC4.3) and point this script at the folder. With no
 * argument it reports over the repo's own fixtures and says so, because a
 * self-made corpus proves nothing about conformance.
 */

import { readFile, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { parseIfcModel } from "../src/lib/bim/ifc-model-loader";

interface FileResult {
  file: string;
  ok: boolean;
  error?: string;
  schema: string | null;
  elements: number;
  withGeometry: number;
  withDeclaredQuantities: number;
  withDerivedQuantities: number;
  unmappedClasses: string[];
  undeclaredUnits: boolean;
  warnings: number;
}

async function collect(dir: string, out: string[] = []): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await collect(full, out);
    else if (entry.name.toLowerCase().endsWith(".ifc")) out.push(full);
  }
  return out;
}

function argValue(flag: string): string | null {
  const i = process.argv.indexOf(flag);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : null;
}

async function main(): Promise<void> {
  const fixtures = path.resolve("src/lib/bim/__tests__/fixtures");
  const requested = process.argv[2];
  const isOwnFixtures = !requested || requested.startsWith("--");
  const corpus = isOwnFixtures ? fixtures : path.resolve(requested);
  if (!existsSync(corpus)) {
    console.error(`Corpus directory not found: ${corpus}`);
    process.exit(1);
  }

  const files = (await collect(corpus)).sort();
  const results: FileResult[] = [];

  for (const file of files) {
    const rel = path.relative(corpus, file);
    try {
      const bytes = new Uint8Array(await readFile(file));
      const result = await parseIfcModel(bytes);
      results.push({
        file: rel,
        ok: result.ok,
        schema: result.schema,
        elements: result.elements.length,
        withGeometry: result.elementsWithGeometry,
        withDeclaredQuantities: result.elementsWithQuantities,
        withDerivedQuantities: result.elementsWithDerivedQuantities,
        unmappedClasses: result.coverage.unmappedClasses.map(
          (c) => `${c.ifcClass} x${c.count}`,
        ),
        undeclaredUnits: result.units.undeclared,
        warnings: result.warnings.length,
      });
    } catch (error) {
      results.push({
        file: rel,
        ok: false,
        error: error instanceof Error ? error.message : String(error),
        schema: null,
        elements: 0,
        withGeometry: 0,
        withDeclaredQuantities: 0,
        withDerivedQuantities: 0,
        unmappedClasses: [],
        undeclaredUnits: false,
        warnings: 0,
      });
    }
  }

  const parsed = results.filter((r) => r.ok).length;
  const lines: string[] = [
    "# IFC conformance report",
    "",
    "Generated by `scripts/ifc-conformance-report.ts` running the real loader",
    "(`parseIfcModel`, web-ifc) over a corpus directory.",
    "",
    isOwnFixtures
      ? "**Corpus: the repository's own fixtures.** This proves the loader's behaviour on hand-built files. It is NOT a conformance result: the official buildingSMART validation corpus has not been run."
      : `**Corpus: \`${path.relative(process.cwd(), corpus)}\`.** Files were read locally; nothing was uploaded.`,
    "",
    `- Files: ${results.length}`,
    `- Parsed: ${parsed}`,
    `- Failed: ${results.length - parsed}`,
    `- Run: ${new Date().toISOString()}`,
    "",
    "| File | Schema | Elements | Geometry | Declared qty | Derived qty | Unmapped classes | Units undeclared |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const r of results) {
    if (!r.ok) {
      lines.push(
        `| ${r.file} | - | - | - | - | - | **FAILED**: ${(r.error ?? "parse error").replace(/\|/g, "\\|")} | - |`,
      );
      continue;
    }
    lines.push(
      `| ${r.file} | ${r.schema ?? "?"} | ${r.elements} | ${r.withGeometry} | ${r.withDeclaredQuantities} | ${r.withDerivedQuantities} | ${r.unmappedClasses.join(", ") || "-"} | ${r.undeclaredUnits ? "yes" : "no"} |`,
    );
  }

  lines.push(
    "",
    "## What this report does and does not say",
    "",
    "- It records what the loader did with each file: parse success, element and",
    "  geometry counts, declared versus derived quantities, unmapped classes and",
    "  undeclared units.",
    "- It does NOT establish IFC conformance. Only buildingSMART's IFC Validation",
    "  Service can, and it requires the official corpus plus a declared scope.",
    "- An unmapped class is reported, never guessed at: the takeoff simply does not",
    "  include it.",
    "",
  );

  const outPath = path.resolve(
    argValue("--out") ?? "docs/ifc-conformance-report.md",
  );
  await writeFile(outPath, lines.join("\n"), "utf8");
  console.log(
    `Wrote ${outPath} (${results.length} files, ${parsed} parsed, ${results.length - parsed} failed)`,
  );
  if (results.length - parsed > 0) process.exitCode = 2;
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
