/**
 * Writes the build-sequence text into a module the prerenderer can import.
 *
 * The diagrams are React SVG, so the only way a crawler sees the method without
 * running JavaScript is for the same step text to exist in the static HTML.
 * Generating it from the sequence module keeps one source of truth: the page,
 * the drawing and the static copy cannot drift apart.
 */
import { writeFileSync } from "node:fs";
import {
  MASONRY_COURSE_SEQUENCE,
  PAVING_SEQUENCE,
  REBAR_CAGE_SEQUENCE,
  ROOF_TRUSS_SEQUENCE,
  SLAB_BUILD_SEQUENCE,
} from "../src/lib/estimation/build-sequence";

type Step = { title: string; detail: string; check?: string };

const escape = (value: string) =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const section = (heading: string, intro: string, steps: Step[]) =>
  `<h2>${escape(heading)}</h2><p>${escape(intro)}</p><ol>${steps
    .map(
      (step) =>
        `<li><strong>${escape(step.title)}</strong>: ${escape(step.detail)}${
          step.check ? ` Check first: ${escape(step.check)}` : ""
        }</li>`,
    )
    .join("")}</ol>`;

const DIAGRAM_INTRO =
  "This page includes a step by step animated build sequence. The same steps are listed here so the method is readable without JavaScript.";

const map: Record<string, string> = {
  "/concrete-takeoff-calculator": section(
    "How a slab is built, step by step",
    DIAGRAM_INTRO,
    SLAB_BUILD_SEQUENCE,
  ),
  "/roof-framing-calculator": section(
    "How the roof goes up, step by step",
    `${DIAGRAM_INTRO} Bracing is shown before sheeting, because bracing is what holds the trusses upright.`,
    ROOF_TRUSS_SEQUENCE,
  ),
  "/masonry-calculator": section(
    "How a block wall goes up, step by step",
    `${DIAGRAM_INTRO} Each course is staggered against the one below, so vertical joints never line up.`,
    MASONRY_COURSE_SEQUENCE,
  ),
  "/paving-calculator": section(
    "How paving is laid, layer by layer",
    `${DIAGRAM_INTRO} The bedding layer levels the pavers; it is never used to correct a bad sub-base.`,
    PAVING_SEQUENCE,
  ),
  "/reinforcement": section(
    "How a reinforcement cage is built, step by step",
    `${DIAGRAM_INTRO} Bar sizes, lengths and spacing come from the engineer's schedule, never from this tool.`,
    REBAR_CAGE_SEQUENCE,
  ),
};

const body = Object.entries(map)
  .map(([path, html]) => `  ${JSON.stringify(path)}: ${JSON.stringify(html)},`)
  .join("\n");

writeFileSync(
  "scripts/build-sequence-content.generated.mjs",
  `// Generated by scripts/generate-sequence-prerender.ts. Do not edit by hand.\nexport const buildSequenceContent = {\n${body}\n};\n`,
);
console.log(`build sequence content: ${Object.keys(map).length} routes`);
