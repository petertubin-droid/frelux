#!/usr/bin/env node
/**
 * Share and PDF coverage across the calculators and estimators.
 *
 * The standing rule is that every calculator offers WhatsApp share and PDF
 * export. That rule is only as real as the pages that honour it, so this counts
 * them instead of assuming. A page counts as covered when it imports one of the
 * share components, or calls the estimate sharing helpers directly.
 *
 * Run: node scripts/audit-share-coverage.mjs [--write]
 * With --write it also refreshes docs/calculator-share-coverage.md.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const PAGES = "src/pages";
const TOOL = /(Calculator|Estimator|Takeoff|Count|Boq|BOQ|Schedule|Timeline|Cost)/i;
const COVERED = [
  "ShareEstimateButton",
  "QuoteShareButton",
  "shareEstimateOnWhatsApp",
  "downloadEstimatePdf",
  "estimate-sharing",
];

const pages = readdirSync(PAGES)
  .filter((f) => f.endsWith(".tsx") && !f.endsWith(".test.tsx"))
  .filter((f) => statSync(join(PAGES, f)).isFile());

const rows = pages.map((file) => {
  const source = readFileSync(join(PAGES, file), "utf8");
  const hits = COVERED.filter((needle) => source.includes(needle));
  return {
    file,
    tool: TOOL.test(file),
    covered: hits.length > 0,
    via: hits[0] ?? null,
  };
});

const tools = rows.filter((r) => r.tool);
const missing = tools.filter((r) => !r.covered);
const pct = tools.length ? Math.round(((tools.length - missing.length) / tools.length) * 100) : 0;

console.log(`tool pages: ${tools.length}`);
console.log(`covered:    ${tools.length - missing.length} (${pct}%)`);
console.log(`missing:    ${missing.length}`);
missing.forEach((r) => console.log(`  ${r.file}`));

if (process.argv.includes("--write")) {
  const body = [
    "---",
    "title: Calculator share and PDF coverage",
    "summary: Which calculators and estimators offer WhatsApp share and PDF export, generated by scripts/audit-share-coverage.mjs. Run the script after wiring more pages.",
    "---",
    "",
    "# Calculator share and PDF coverage",
    "",
    "Standing rule: every calculator and estimator offers WhatsApp share and PDF",
    "export. This file is generated, not hand written. Regenerate with:",
    "",
    "```bash",
    "node scripts/audit-share-coverage.mjs --write",
    "```",
    "",
    `Tool pages found: ${tools.length}`,
    "",
    `Covered: ${tools.length - missing.length} (${pct}%)`,
    "",
    `Missing: ${missing.length}`,
    "",
    "## Pages still to wire",
    "",
    missing.length ? missing.map((r) => `- \`src/pages/${r.file}\``).join("\n") : "None.",
    "",
    "## How to wire one",
    "",
    "```tsx",
    '<ShareEstimateButton estimate={{ kind: "Tile Cost Estimate", summaryLines, totals }} />',
    "```",
    "",
    "Build the estimate from the page's own result object. The component never",
    "recomputes an estimate, so the strings must come from the calculation itself.",
    "",
  ].join("\n");
  writeFileSync("docs/calculator-share-coverage.md", body);
  console.log("\nwrote docs/calculator-share-coverage.md");
}
