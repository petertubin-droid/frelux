## The questions that come up on site

**What if the reveal is out of square by twenty millimetres?** Order to the smallest width and note the difference, or change to an over the face fit. A blind ordered to the average will bind at one side within a week.

**Can I measure from a photograph?** Only for a rough idea of type and layout. A photograph has no scale and lens distortion makes a wide window look like a tall one. No factory will accept it.

