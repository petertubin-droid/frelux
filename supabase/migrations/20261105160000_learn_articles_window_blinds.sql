Every blind is made to a number. There is no such thing as a standard size, no returns policy that covers a window measured twice as wide as it is, and no way to make a blind that is five millimetres too long fit a reveal that will not give. The factory cuts the tube, cuts the fabric, cuts the headrail, and packs it, all from what you wrote down. If the number is wrong, the whole product is wrong, and the only person who eats the cost is the one who wrote it.

That is why blind suppliers treat measurement as a separate trade. Fitters who measure every day still take three readings across the same opening, still check the depth of the reveal with the same steel rule they have used for years, and still photograph the window with the tape in place. It is not caution for its own sake. It is the cheapest insurance in the job.

This guide sets out the method properly. It covers the two ways a blind can sit in a window, the readings that matter, the obstructions that catch people out, the clearances each blind type needs, and the way to record a whole house so nothing has to be measured twice. When you have your numbers, the FRELUX window blind estimator turns them into a priced schedule, per window and for the whole job.

## The two fits, and why the choice comes first

Before the tape comes out, decide how the blind will sit. There are only two options and everything else follows from them.

**Inside the reveal.** The blind is fitted within the recess the window sits in, so it hangs close to the glass. It looks built in, it does not use wall space, and it suits deep reveals with clean plaster. The blind must be slightly narrower than the reveal so it can move, which leaves small light gaps at the edges. Roller, venetian, day and night, and pleated blinds all work inside a reveal if there is enough depth.

**Over the face.** The blind is fixed to the wall or frame in front of the reveal and covers the opening completely, overlapping the plaster on all four sides. It blocks far more light, hides an untidy reveal, and allows a wider blind than the recess would take. Roller and roman blinds are the usual choice here, and blackout work almost always needs it.

The trap is measuring one way and ordering the other. A blind measured inside the reveal and then fitted outside will be short at both edges and hang in the wrong place. Decide first, write the decision at the top of the schedule, and measure only for that method.

## What you need before you start

A steel tape of at least five metres, because cloth tapes stretch and cheap tapes have loose hooks. A pencil and a printed schedule or a phone note you will not lose. A step ladder that reaches the head of the window comfortably. A torch for dark reveals. A camera, because a photograph of each opening with the tape visible settles arguments later.

Two rules make the readings trustworthy. Measure in millimetres, always, even if the customer speaks in feet and inches, because blind manufacturing works in millimetres and a conversion at the end is where errors creep in. And measure the opening, not the glass, not the old blind, and not the curtain track.

## Measuring inside the reveal

Take three widths: at the top, in the middle, and at the bottom. Take three drops: on the left, in the centre, and on the right. Write down the smallest width and the smallest drop, then check that no reading differs by more than about ten millimetres. A reveal that varies more than that is out of square or the plaster is uneven, and the blind should be ordered to the smallest figure with a note, or the fit changed to over the face.

Depth matters as much as width. Measure from the back of the reveal, where the window frame sits, to the face of the wall. Each blind type needs a minimum depth to sit clear of the glass and clear of handles: a roller with a standard bracket wants about fifty millimetres, a venetian with a fifty millimetre slat and its headrail wants sixty to seventy, day and night needs a similar figure for the cassette, and a vertical blind with ninety millimetre vanes wants around a hundred. If the reveal is shallower than that, the blind will stand proud of the wall or foul the handle, and over the face is the better answer.

## Measuring over the face

Here you are measuring the opening you want to cover, then adding overlap. Measure the width of the reveal at its widest and the drop from the highest point to the lowest, then add roughly fifty millimetres at each side and the same at the top. At the bottom, decide where the blind should finish: at the sill, past it, or at the floor. For a blackout blind in a bedroom, past the sill and wide overlap reduces the light gap to a thin line at the edges, which is the best a face fixed blind can do without side channels.

Check what is in the way. Wall lights, sockets, radiators, curtain poles, furniture and wardrobes all sit where a projecting blind wants to be. A blind that lands on a radiator will be discoloured within a year; one that lands on a wardrobe will not open.

## The obstructions that cause remakes

Handles are the single most common cause of a remake. A window handle projects from the frame and a blind hanging inside the reveal will foul it, either stopping the sash from opening or catching the fabric. Measure the projection of the handle from the frame and add that to the clearance the blind needs. If the reveal cannot take a blind plus the handle, either fit the blind over the face or change the handle to a low profile one, which is cheaper than changing the blind.

Tiles, beads of plaster, gas struts on roof windows, trickle vents, sash horns, and window opening casements that move outwards all take space. Photograph the head of the window before ordering. A photograph costs nothing and answers the question the factory will ask.

## Openings that need special care

Bay windows are three or more faces meeting at angles, and each face needs its own blind and its own measurement. Measure each face inside the reveal, and check the angles: a bay that is not a true ninety degrees will need the blinds to be made to the face width and fitted closely, or the corners will show gaps.

Sliding doors and patio doors usually want a vertical blind or a panel blind, fixed to the ceiling or the wall above the frame, with the vanes stacked to one side. Measure the full width of the opening plus the stack space, because the vanes need somewhere to gather, and check the direction the door slides so the stack does not block the handle.

Tilt and turn windows and doors with a low handle want an over the face fit or a blind with a tensioned side channel, and casement windows that open outwards need the blind clear of the swing.

## When to measure

Measure after plastering, tiling and painting are finished, not before. A reveal that becomes fifteen millimetres smaller after tiling will not accept a blind measured against the bare blockwork. If the site is not ready, measure against the finished line and confirm again before the order goes in.

For a new build, take measurements at the end of first fix, then re-measure after the finished floor and tiling are complete. Two visits cost less than one remake, every time.

