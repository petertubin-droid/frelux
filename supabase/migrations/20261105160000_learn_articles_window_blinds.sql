## Measured area and chargeable area

The measured area is width times drop. The chargeable area is what the factory is paid for, and it is always larger, because a blind is not made from a rectangle exactly the size of the window.

Fabric must wrap the tube, be hemmed, pass the bottom rail, and clear the brackets. On a roman it must fold, and the folds consume length. On a patterned fabric it must be cut so the pattern lines up at the top and repeats across the drops. All of that is waste allowance, and it varies by type.

A rigid venetian has almost no waste because slats are cut to width and the surplus is trivial. A roller carries a modest allowance. A roman in a large repeat can carry a very large one. That is why the same window prices differently across three types even at the same rate per square metre.

## Pattern repeat, and the expensive arithmetic

Pattern repeat is the distance before a fabric pattern repeats. A small textured weave might repeat every ten centimetres, a large floral every sixty.

When several drops are cut from the same fabric and hung side by side, as on a wide window split into panels, or on a set of matching blinds in one room, the pattern must line up across the seams. To achieve that, each drop is cut to a whole number of repeats, and any surplus is discarded. A 1.4 metre drop in a 0.6 metre repeat becomes a 1.8 metre cut, and 0.4 metres of every drop is thrown away.

Ask the supplier what repeat the chosen fabric has and whether the quote allows for matching. A quote that ignores the repeat is a quote that will either look wrong or be re-priced later.

## Cut direction and railroaded fabric

Some fabrics are woven so that the pattern runs along the length of the roll only. Others can be turned through ninety degrees, which is called railroaded, and that allows a wide blind to be cut in one piece without seams.

Cut direction affects both the look and the waste. A plain fabric cut the wrong way shows a visible change in shade when it meets another panel. A striped fabric cut across the roll has stripes running horizontally, which is a design decision nobody should discover at fitting.

