A blind quote looks like it should be simple. The shop has a rate per square metre on the wall, the window has an area, and the two multiply. Customers expect that, and suppliers know the arithmetic almost never works out that way.

The reason is a second rule that sits underneath the first: a minimum charge per window. Every blind, no matter how small, consumes a headrail, brackets, screws, a control chain or wand, a fabric cut, a packed carton, a slot in the van, and a fitter's hour at the wall. Those costs do not shrink with the window. Below a certain size the rate per square metre would pay for the fabric and nothing else, so the minimum takes over.

Once you see both rules, most of the surprising behaviour in blind pricing becomes predictable: why a tiny bathroom window costs as much as a living room one, why a house priced per window looks cheaper than the same house priced per metre, and why two suppliers quoting the same room differ by a third. The FRELUX window blind estimator shows both on the same page, and the smallest window in the schedule usually reveals which rule the quote is resting on.

## What the minimum actually covers

Break a blind into the parts you pay for and the picture is clear. Fabric is the visible element, but it is rarely the dominant one on small openings.

**The headrail and mechanism.** Every type has a housing: a tube for a roller, a cassette for day and night, a headrail with carriers for a vertical blind, a slat track for a venetian. That housing is made in fixed profiles and priced per unit, not per metre of window.

**The hardware kit.** Brackets, screws, wall plugs, chain, tensioner, child safety devices, bottom rail and weights. A kit for a 500 millimetre window is the same kit as for a 2,000 millimetre one, sometimes larger because short drops need more weight to handle.

**Labour that does not scale.** Cutting, hemming, punching, assembly, quality check, packing, invoicing, and the fitter who must drive to the address, protect the floor, drill four or six holes, level the blind, adjust the chain and take the ladder away. A half hour at the wall costs the same whether the blind above it is half a metre or two.

**Risk and warranty.** A supplier who returns to fix a blind carries that cost across the whole order book. Small orders carry the same risk per line as large ones.

Put those together and the minimum stops looking like a penalty and starts looking like arithmetic.

## The crossover point

There is a window size below which the minimum governs, and above which the rate governs. Where that crossover sits depends on the rate, the minimum and the waste allowance, but for ordinary day and night and roller blinds it usually lands somewhere around one and a half to two square metres. Below it, extra width is nearly free. Above it, every centimetre costs money.

That single fact explains a lot of customer confusion. Someone ordering four small bedroom windows may find the price per window is the same as a larger living room window, and conclude the shop is overcharging the small rooms. In fact the small windows are being sold at cost plus the minimum, and the large window is being sold at the rate. The two numbers coincide because the crossover is doing its work.

The estimator prints the minimum for each row and states plainly when it applied, so the conversation moves from suspicion to arithmetic.

## A worked schedule without prices in it

Take four windows: a bathroom at 600 by 900 millimetres, a bedroom at 1,200 by 1,350, a living room at 2,400 by 1,500, and a patio door at 2,400 by 2,100.

The bathroom is 0.54 square metres, which will be priced at the minimum. The bedroom is 1.62, which lands near the crossover and may still be raised to the minimum depending on the type. The living room is 3.6 and is priced on the rate. The patio door is 5.04 and is priced on the rate with the largest share of the whole order.

The lesson for the customer is that the two small openings are not getting cheaper by much, and the lesson for the installer is that a job made only of bathroom windows is barely worth taking at list prices. Both need to see the same table.

## Waste makes the gap wider or narrower depending on type

The waste allowance is the area added to the measured opening so the finished blind has enough material to clear the hardware and, where there is one, to match a pattern. It varies by type: a rigid venetian slat needs very little, a roller takes a modest allowance for the hem and the roll, and a roman or a day and night blind in patterned fabric can need substantially more because the pattern has to line up across the folds.

Waste interacts with the minimum in a way worth understanding. A type with a high waste allowance reaches its rate-driven price at a slightly smaller window, because more chargeable area accumulates sooner. A type with practically no waste, such as a venetian, stays at its minimum for longer. That is one of the reasons a cheap looking type is not always the cheaper quote on small windows.

## Hardware and controls scale differently

Width changes hardware more than height. A wide roller needs a stronger tube and more brackets, a wide day and night needs a heavier cassette and often a centre support, and a wide vertical blind needs more carriers and a longer track. Height changes the chain length, the amount of fabric and the stack, which is cheaper per unit of area than width.

This is why two windows of the same area do not necessarily cost the same. A short, wide window and a tall, narrow one can measure identically and price differently, because the hardware responds to the width. When a customer compares two rooms, compare like with like.

## Motors, cassettes and the extras question

Motors are the clearest example of a cost that ignores size. A motor has a rating and a price, and a motor for a small window costs nearly what a motor for a large one costs. The estimator does not invent a motor price: it asks for the figure you were quoted and adds it per motorised window, because motor pricing varies more by supplier than by window.

The same applies to cassette headrails, which enclose the rolled fabric and cost a fixed amount per window, and to removal of old blinds, which is labour per window and has nothing to do with area.

## Presenting it to a customer

The worst way to quote blinds is a single total. The second worst is a per metre rate with a total below it. Both invite the customer to do arithmetic that will not match yours.

