Most blind decisions start in the wrong place: a showroom, a catalogue or a photograph of somebody else's room. They should start with four questions about the window itself.

**What does the room need the blind to do?** Block light for sleep, cut glare on a screen, give privacy from a neighbour, hide an ugly view, keep heat out, or simply look finished.

**What is the window like?** Deep reveal or shallow, wide or tall, opening casement or fixed pane, patio slider or roof light, handle projecting into the space or flush.

**What is the room like?** Steam and grease in a kitchen, splash in a bathroom, dust and traffic in a hallway, afternoon sun in a west facing bedroom, salt air on a coast.

**How will it be operated?** A chain at arm height, a wand, a motor, a cord that a child can reach, a window that opens behind the blind.

Answer those and the type usually chooses itself. The rest of this guide takes each type in turn and says what it is good at, what it is bad at, and where it belongs.

## Roller blinds: the default for good reason

A roller is a tube of fabric that rolls up around itself, controlled by a chain, a spring or a motor. It is the most space efficient blind made: the fabric occupies a few cubic centimetres at the head of the window and nothing else.

**Good at:** clean lines, large uninterrupted surfaces, blackout when the fabric is blackout coated, easy cleaning, low cost per square metre on larger windows, and compatibility with motors and smart control.

**Weak at:** light gaps at the edges when fitted inside a reveal, no adjustment of the light once the blind is part way down, and a fabric that can crease if left rolled in one position for years.

**Suits:** living rooms, studies, rented flats, offices, anywhere a plain surface and a wide view matter. Blackout coated roller is the standard choice for a bedroom where the window is not critical and a small light gap is acceptable.

**Watch for:** the roll direction. A standard roll sits behind the fabric, which pushes it away from the glass; a reverse roll sits in front, which brings the fabric closer to the glass and is the right choice where a sill or a handle is in the way. Get this wrong and the blind will not clear the window furniture.

## Zebra blinds: bands of sheer and solid

A zebra blind, sometimes called a banded or striped blind, is a loop of fabric made of alternating sheer and opaque horizontal bands. As the blind moves, the bands align to open the view or overlap to close it. Two layers of fabric run in front of each other, both visible, and the effect is a soft horizontal line across the window.

**Good at:** controlling privacy and view without losing daylight entirely, modern appearance, hiding an unattractive outlook while keeping brightness.

**Weak at:** not blackout, not even close. The sheer bands always let light through, and the horizontal lines are a visual statement a customer either loves or rejects within seconds. Dust settles in the bands. The mechanism has more parts than a roller and more to go wrong.

**Suits:** living rooms, dining rooms, home offices, shopfronts where the glass should stay visible but the interior should not be readable from the street.

**Watch for:** band alignment. A cheap zebra whose bands drift out of level is a permanent irritation, and it cannot be fixed by adjustment once the fabric has stretched.

## Day and night blinds: the same idea, better controlled

Day and night blinds, also sold as duo or vision blinds, use the same alternating band principle but house the fabric in a cassette at the top and usually run it on a tensioned or guided system. The cassette protects the fabric, the blind travels more smoothly, and the overlap control is finer.

**Good at:** precise control of privacy and light, tidy appearance with the cassette hiding the mechanism, better performance on wide windows than a bare zebra.

**Weak at:** cost per square metre above a roller, a cassette that needs clearance at the head, and the same fundamental limit: the sheer bands never become opaque.

**Suits:** bedrooms where some light is acceptable, living rooms, and any window where the customer wants to see out without being seen in.

**Watch for:** the depth needed for the cassette, usually more than a roller, and the drop loss at the top. A short window loses a noticeable amount of clear opening to the cassette, which matters above kitchen counters and in dormer windows.

## Venetian blinds: the adjustable classic

Venetians are horizontal slats suspended on ladders and tilted by a wand or a cord. Aluminium slats commonly come in 15, 25 and 50 millimetre widths. The narrow slat gives a fine line and precise light control; the wide slat gives a bolder look and suits bigger windows.

**Good at:** the finest light control of any type, since the slats tilt rather than the blind travelling, ventilation through open slats, and easy cleaning of aluminium in a kitchen.

**Weak at:** dust on every slat, cords and ladders that can wear, noise in a draught, and a look that some customers find dated. Aluminium slats can bend.

**Suits:** kitchens, bathrooms, studies, offices, and any window where the user wants to angle light rather than exclude it.

**Watch for:** slat width against window size. Fifteen millimetre slats on a two metre wide window read as busy and flimsy; fifty millimetre slats on a small bathroom window look coarse. Also check the cord safety requirement in your market and use a tensioned or wand control where children are present.

## Faux wood and real wood

Faux wood is a composite that imitates timber, usually in wide slats, and tolerates moisture far better than real wood. Real wood is warmer and heavier, and it moves with humidity.

**Good at:** looking substantial, suiting period rooms, wide slats that read as joinery rather than window dressing.

**Weak at:** weight, which stresses brackets and makes wide blinds hard to operate; real wood can warp, twist or craze in a steamy bathroom or a hot conservatory. Faux wood is heavy too, and cheap versions yellow.

**Suits:** living rooms, studies, bay windows in older houses, anywhere the wood look belongs.

**Watch for:** the weight on a wide window. Above a certain width a wood or faux wood blind needs intermediate brackets or a different type entirely, and the quote should say so.

## Vertical blinds: made for wide openings

Vertical blinds hang vanes from a track and rotate them, then draw them to one side. They are the only type that handles a patio slider properly, because the vanes stack into a small space and the door can still open.

**Good at:** very wide openings, sliding doors, floor to ceiling glazing, offices where the view must stay available, cheap coverage per square metre on large spans.

**Weak at:** vanes that swing in a draught, a stack that occupies part of the opening, and a look that is hard to make domestic. Dust collects on the bottom weights.

**Suits:** patio doors, balcony sliders, offices, clinics, meeting rooms, shopfronts.

**Watch for:** stack direction against traffic and handles, and the headroom the track needs. On a slider, the stack should sit on the fixed panel side, not the opening side.

## Roman, pleated and panel blinds

**Roman blinds** are fabric panels that fold up in horizontal pleats. They bring softness and pattern to a room, and they suit large traditional windows, but they need stack room above the window and they are the worst type for a wet room. A patterned roman carries a substantial waste allowance, because the pattern must line up across the folds, which is why roman quotes often look high per square metre.

**Pleated blinds** are lightweight, thin and ideal for conservatories, roof windows and awkward shapes such as arches and angled heads. They offer top down bottom up control, which is useful for privacy with daylight, but the pleats collect dust and the cords need care.

**Panel blinds** are wide fabric panels that slide on a track, used for very large glazed walls and room dividers. They are a design statement with a price to match, and they need generous stacking space.

## Room by room, in one table

**Kitchen:** aluminium venetian or a wipe clean roller. Grease settles into fabric, so avoid roman and pleated.
**Bathroom:** aluminium venetian, faux wood or a moisture tolerant roller. Real wood and fabric will suffer.
**Bedroom:** blackout roller, day and night, or a roman with a blackout lining. Decide how much light the sleeper actually tolerates.
**Living room:** roller, zebra, day and night, or roman. The view and the style of the room decide more than the technical spec.
**Home office:** venetian or day and night, because both allow light without glare on a screen.
**Patio door:** vertical or panel. Nothing else draws out of the way properly.
**Conservatory or roof window:** pleated, ideally with a tensioned side channel.

