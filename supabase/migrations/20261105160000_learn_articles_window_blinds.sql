## When a small job is worth taking

Every installer has a floor. Below a certain value, a job costs more in travel, parking, admin and warranty than it returns. The minimum charge per window exists because suppliers have that floor too. Knowing where yours sits is useful: a job of nine small windows may be worth having, while a single small window as a separate visit often is not, and quoting it at a fair minimum is honest rather than greedy.

