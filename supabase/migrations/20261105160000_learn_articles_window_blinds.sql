## Grade, and why the same window has three prices

The same window really does have three prices, and they are not a trick. Standard stock, premium print and a designer range are different products. In the Nigerian market, premium day and night lists price a small window at a figure that works out to a materially higher rate per square metre than ordinary stock, and the estimator applies grade as a multiplier on the rate, never on the minimum, because a shop that charges a minimum does not raise it by a fixed percentage for better fabric.

